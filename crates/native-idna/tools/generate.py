#!/usr/bin/env python3
"""Generate only data tables from the pinned official Unicode files, offline.
Workglen implementation, Apache-2.0. Data: Unicode-3.0, see LICENSE-UNICODE.
No Python Unicode database or third-party implementation is used.
"""
from pathlib import Path
import hashlib, json, sys
ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'data'

def fields(name):
    for line in (DATA / name).read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if line:
            yield [v.strip() for v in line.split(';')]

def span(value):
    pair = value.split('..')
    return int(pair[0], 16), int(pair[-1], 16)

def escaped(values):
    return '"' + ''.join('\\u{%x}' % c for c in values) + '"'

def ranges(values, default):
    start, prior = 0, values[0]
    out = []
    for i, value in enumerate(values[1:], 1):
        if value != prior:
            if prior != default:
                out.append((start, i - 1, prior))
            start, prior = i, value
    if prior != default:
        out.append((start, len(values)-1, prior))
    return out

out = ['// @generated by tools/generate.py; do not edit.\n'
       '// Unicode 18.0.0 data © 1991–2026 Unicode, Inc. Unicode-3.0; see LICENSE-UNICODE.\n']
out.append('pub static MAPPING: &[(u32,u32,u8,&str)] = &[\n')
statuses = {'valid':0, 'mapped':1, 'ignored':2, 'disallowed':3, 'deviation':4}
previous = -1
for row in fields('IdnaMappingTable.txt'):
    a,b=span(row[0]); assert a == previous+1; previous=b
    mapping=[int(s,16) for s in row[2].split()] if len(row)>2 else []
    out.append(f'({a},{b},{statuses[row[1]]},{escaped(mapping)}),\n')
assert previous == 0x10ffff
out.append('];\n')
ccc=[0]*0x110000; mark=[0]*0x110000; decomposition={}
for row in fields('UnicodeData.txt'):
    c=int(row[0],16)
    if row[1].endswith(', First>'):
        first=c; continue
    a=first if row[1].endswith(', Last>') else c
    for cp in range(a,c+1): ccc[cp]=int(row[3]);mark[cp]=int(row[2].startswith('M'))
    if row[5] and not row[5].startswith('<'): decomposition[c]=tuple(int(s,16)for s in row[5].split())
excluded=set()
for row in fields('DerivedNormalizationProps.txt'):
    if row[1]=='Full_Composition_Exclusion':
        a,b=span(row[0]);excluded.update(range(a,b+1))
def expand(c):
    if c in decomposition: return tuple(v for d in decomposition[c] for v in expand(d))
    return (c,)
out.append('pub static DECOMPOSITION: &[(u32,&str)] = &[\n')
for c in sorted(decomposition): out.append(f'({c},{escaped(expand(c))}),\n')
out.append('];\npub static COMPOSITION: &[(u64,u32)] = &[\n')
compositions=sorted(((d[0]<<21)|d[1],c)for c,d in decomposition.items()if c not in excluded and len(d)==2)
assert len({k for k,v in compositions})==len(compositions)
for k,c in compositions:out.append(f'({k},{c}),\n')
out.append('];\n')
bidi_names=['L','R','AL','EN','ES','ET','AN','CS','NSM','BN','B','S','WS','ON','LRE','LRO','RLE','RLO','PDF','LRI','RLI','FSI','PDI']
bidi=[0]*0x110000
long={'Left_To_Right':'L','Right_To_Left':'R','Arabic_Letter':'AL','European_Terminator':'ET'}
for line in (DATA/'DerivedBidiClass.txt').read_text().splitlines():
    if line.startswith('# @missing:'):
        region,value=line.split(':',1)[1].split(';');a,b=span(region.strip());v=bidi_names.index(long[value.strip()]);bidi[a:b+1]=[v]*(b-a+1)
for row in fields('DerivedBidiClass.txt'):
    a,b=span(row[0]);bidi[a:b+1]=[bidi_names.index(row[1])]*(b-a+1)
joining=[0]*0x110000;join_names=['U','L','R','D','T','C']
for row in fields('DerivedJoiningType.txt'):
    a,b=span(row[0]);joining[a:b+1]=[join_names.index(row[1])]*(b-a+1)
for name,values in [('CCC',ccc),('MARK',mark),('BIDI',bidi),('JOINING',joining)]:
    out.append(f'pub static {name}: &[(u32,u32,u8)] = &[\n')
    for a,b,v in ranges(values,0):out.append(f'({a},{b},{v}),\n')
    out.append('];\n')
manifest={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(DATA.glob('*.txt'))}
outputs={'src/tables.rs':''.join(out),'data/SHA256.json':json.dumps({'unicode_version':'18.0.0','sources':manifest},indent=2)+'\n'}
for name,value in outputs.items():
    if '--check' in sys.argv:
        assert (ROOT/name).read_text()==value, f'Regeneration mismatch: {name}'
    else:
        (ROOT/name).write_text(value)
print('Verified' if '--check'in sys.argv else 'Generated', 'Unicode 18 tables:', (ROOT/'src/tables.rs').stat().st_size, 'bytes')

